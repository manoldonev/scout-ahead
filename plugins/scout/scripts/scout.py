#!/usr/bin/env python3
"""scout: state and artifacts for exploratory work.

One folder per scout under scouting/<slug>/. state.json is the source of truth;
log.md, decisions.md and handoff.md are rendered from it on every change, so
nothing in them is ever out of step with what the commands recorded.

Pointers, not copies: branches, commits, file:line, transcript paths.
"""
import argparse
import datetime as dt
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

STATE = "state.json"
CURRENT = ".current"
SESSION = ".session.json"
HANDOFF_VERSION = 1
GENERATED = "<!-- generated by scout from state.json; edits here are overwritten, use `scout note` / `scout decide` -->"


# ---------------------------------------------------------------- helpers

def now():
    return dt.datetime.now(dt.timezone.utc).replace(microsecond=0).isoformat()


def short(ts):
    return ts[:16].replace("T", " ") + "Z" if ts else "?"


def die(msg, code=2):
    print(f"scout: {msg}", file=sys.stderr)
    sys.exit(code)


def git(args, cwd=None, check=True):
    r = subprocess.run(["git", *args], cwd=cwd, text=True, capture_output=True)
    if check and r.returncode != 0:
        die(f"git {' '.join(args)} failed: {r.stderr.strip()}")
    return r.stdout.strip()


STDIN_FIELDS = ("text", "evidence", "learned", "verdict_note", "repro", "blast_radius")


def _text(v):
    return sys.stdin.read().rstrip("\n") if v == "-" else v


def read_stdin_fields(args):
    """`-` reads the value from stdin, so operator words reach the record without shell quoting."""
    dashed = [f for f in STDIN_FIELDS if getattr(args, f, None) == "-"]
    if len(dashed) > 1:
        die("only one argument per call can be read from stdin; got '-' for " + ", ".join(dashed))
    for f in dashed:
        setattr(args, f, _text(getattr(args, f)))


def head_commit(top):
    return git(["rev-parse", "--verify", "--quiet", "HEAD"], cwd=top, check=False) or None


def toplevel(cwd=None):
    r = subprocess.run(["git", "rev-parse", "--show-toplevel"], cwd=cwd, text=True, capture_output=True)
    return Path(r.stdout.strip()) if r.returncode == 0 else Path(cwd or os.getcwd()).resolve()


def scouts_root(args):
    root = Path(args.root) if getattr(args, "root", None) else toplevel()
    return root / "scouting"


def slugify(text, limit=40):
    s = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    if len(s) > limit:
        cut = s[:limit + 1].rfind("-")
        s = s[:cut] if cut > 0 else s[:limit]
    return s.rstrip("-") or "scout"


def load(root, slug):
    p = root / slug / STATE
    if not p.exists():
        die(f"no scout '{slug}' under {root}")
    return normalize(json.loads(p.read_text()))


def normalize(st):
    """Upgrade older state shapes in place: questions parked before ids existed get Q1..Qn by position."""
    for i, q in enumerate(st.get("questions", []), 1):
        q.setdefault("id", f"Q{i}")
    return st


def save(root, st):
    d = root / st["slug"]
    d.mkdir(parents=True, exist_ok=True)
    st["updated_at"] = now()
    (d / STATE).write_text(json.dumps(st, indent=2) + "\n")
    (d / "log.md").write_text(render_log(st))
    (d / "decisions.md").write_text(render_decisions(st))
    # handoff.md is rendered only by the handoff command: it carries a written-at stamp,
    # and re-rendering it on every save churned the file with no content change.


def current_slug(root, explicit=None, allow_closed=True):
    if explicit:
        return explicit
    p = root / CURRENT
    if p.exists() and (root / p.read_text().strip() / STATE).exists():
        return p.read_text().strip()
    open_ = [s for s in list_scouts(root) if s["status"] == "open"]
    if len(open_) == 1:
        return open_[0]["slug"]
    if not open_:
        if allow_closed:
            closed = sorted(list_scouts(root), key=lambda s: s.get("updated_at", ""))
            if closed:
                return closed[-1]["slug"]
        die("no open scout; run `scout start <question>` first")
    die("several open scouts; pass --scout <slug>: " + ", ".join(s["slug"] for s in open_))


def set_current(root, slug):
    root.mkdir(parents=True, exist_ok=True)
    (root / CURRENT).write_text(slug + "\n")
    gi = root / ".gitignore"
    if not gi.exists():
        gi.write_text(f"{SESSION}\n")


def list_scouts(root):
    out = []
    if not root.exists():
        return out
    for d in sorted(root.iterdir()):
        if (d / STATE).exists():
            out.append(normalize(json.loads((d / STATE).read_text())))
    return out


def cur_direction(st):
    return st["directions"][-1]


def evidence_label(d):
    ev = d.get("evidence")
    if not ev:
        return ""
    ev = " ".join(ev.splitlines())
    if d.get("at_commit"):
        ev += f" @ {d['at_commit'][:12]}" + ("+dirty" if d.get("dirty") else "")
    return ev


def branch_exists(b, top):
    return subprocess.run(["git", "rev-parse", "--verify", "--quiet", b], cwd=top, capture_output=True).returncode == 0


def branch_mark(b, base, top):
    if not b or top is None:
        return ""
    if not branch_exists(b, top):
        return " (missing)"
    if base and git(["rev-list", "--count", f"{base}..{b}"], cwd=top, check=False) == "0":
        return " (no commits past base)"
    if subprocess.run(["git", "rev-parse", "--abbrev-ref", f"{b}@{{u}}"], cwd=top, capture_output=True).returncode != 0:
        return " (not pushed)"
    return ""


def transcript_mark(p):
    if not p:
        return ""
    return " (local to this machine)" if Path(p).exists() else " (missing)"


def by_label(d):
    if d["by"] == "code" and d.get("proof"):
        return f"code, {d['proof']}"
    return d["by"]


def superseded_label(d):
    sb = d.get("superseded_by")
    if sb is None:
        return ""
    return f"direction {sb}" if isinstance(sb, int) else str(sb)


def open_decisions(st):
    return [d for d in st["decisions"] if d["by"] == "open" and not d.get("superseded_by")]


def live_decisions(st):
    return [d for d in st["decisions"] if not d.get("superseded_by")]


def criteria(st):
    return ([(f"K{i}", t) for i, t in enumerate(st["kill"], 1)]
            + [(f"P{i}", t) for i, t in enumerate(st.get("keep") or [], 1)])


def criteria_lines(st, keep_label, kill_label):
    L = []
    for label, prefix in ((keep_label, "P"), (kill_label, "K")):
        items = [f"{cid} {t}" for cid, t in criteria(st) if cid.startswith(prefix)]
        if items:
            L.append(f"{label}: " + "; ".join(items) + ".")
    return L


def open_questions(st):
    return [q for q in st["questions"] if not q.get("answered")]


def question_label(q):
    return f"{q['id']}: {q['text']}" + (f" (proceeding on: {q['assuming']})" if q.get("assuming") else "")


def open_stubs(st):
    return [s for s in st.get("stubs", []) if not s.get("unstubbed")]


def direction_outcome(d):
    parts = []
    if d.get("learned"):
        parts.append(f"learned: {d['learned']}")
    if d.get("evidence"):
        parts.append(f"turned on: {evidence_label(d)}")
    return "; ".join(parts)


def read_session_file(root):
    p = root / SESSION
    if p.exists():
        try:
            return json.loads(p.read_text())
        except json.JSONDecodeError:
            return None
    return None


def record_session(st, sess):
    if not sess or not sess.get("session_id"):
        return
    if any(s["session_id"] == sess["session_id"] for s in st["sessions"]):
        return
    st["sessions"].append({
        "session_id": sess["session_id"],
        "transcript_path": sess.get("transcript_path"),
        "recorded_at": now(),
    })


def hours_elapsed(st):
    start = dt.datetime.fromisoformat(st["opened_at"])
    end = dt.datetime.fromisoformat(st["closed_at"]) if st.get("closed_at") else dt.datetime.now(dt.timezone.utc)
    return (end - start).total_seconds() / 3600


def box_line(st):
    b = st["box"]
    sp = st["spent"]
    h = f"{sp['hours']:.1f}/{b['hours']}h logged" if b.get("hours") is not None else f"{sp['hours']:.1f}h logged"
    u = f"${sp['usd']:.2f}/${b['usd']} spawn-metered" if b.get("usd") is not None else f"${sp['usd']:.2f} spawn-metered"
    return f"{h}, {u}, {hours_elapsed(st):.1f}h on the calendar"


def breaches(st):
    """One line per clock that rang. A closed scout has nothing left to pivot or close."""
    if st["status"] != "open":
        return []
    b, sp = st["box"], st["spent"]
    out = []
    if b.get("usd") is not None and sp["usd"] >= b["usd"]:
        out.append(f"BOX: ${sp['usd']:.2f}/${b['usd']:g} spawn-metered. Pivot or close.")
    if b.get("hours") is not None:
        if sp["hours"] >= b["hours"]:
            out.append(f"BOX: {sp['hours']:.1f}/{b['hours']:g}h logged. Pivot or close.")
        cal = hours_elapsed(st)
        if cal > b["hours"]:
            out.append(f"BOX: {cal:.1f}h on the calendar against a {b['hours']:g}h box ({sp['hours']:.1f}h logged). Pivot or close.")
    return out


# ---------------------------------------------------------------- renders

def render_log(st):
    L = [f"# Scout: {st['question']}", "", GENERATED, ""]
    if st.get("stakes"):
        L.append(f"Stakes: {st['stakes']}")
    L.append(f"Opened {short(st['opened_at'])} on branch `{st['branch'] or '(no branch)'}` from `{st['base'][:12] if st['base'] else '?'}`.")
    b = st["box"]
    L.append(f"Box: {b.get('hours', '—')} hours, ${b.get('usd', '—')}. Spent: {box_line(st)}.")
    L += criteria_lines(st, "Keep if", "Kill when")
    if not st["kill"]:
        L.append("Kill when: (no kill criteria recorded).")
    L.append(f"Status: {st['status']}" + (f" ({st['outcome']})" if st.get("outcome") else "") + ".")
    L.append("")
    for i, d in enumerate(st["directions"], 1):
        L.append(f"## Direction {i}: {d['text']}")
        L.append("")
        L.append(f"Opened {short(d['opened_at'])}.")
        for e in d["entries"]:
            L.append(f"- {short(e['at'])} {e['kind']}: {e['text']}")
        if d.get("closed_at"):
            how = d.get("closed_by", "pivot")
            L.append(f"- {short(d['closed_at'])} closed by {how}. Learned: {d.get('learned') or '(nothing recorded)'}"
                     + (f"; turned on: {evidence_label(d)}" if d.get("evidence") else ""))
        L.append("")
    if st.get("variants"):
        L.append("## Variants")
        L.append("")
        for run in st["variants"]:
            L.append(f"Run {short(run['at'])}: {run['n']} arms, ${run['cap_usd']} cap each, model {run['model']}. Question: {run['question']}")
            L.append("")
            L.append("| arm | branch | cost | turns | files | result |")
            L.append("|---|---|---|---|---|---|")
            for a in run["arms"]:
                L.append(f"| v{a['i']} | `{a['branch']}` | ${a.get('cost_usd', 0):.2f} | {a.get('turns', '?')} | {a.get('files_changed', '?')} | {a.get('status', '?')} |")
            L.append("")
            L.append(f"Outputs under `scouting/{st['slug']}/variants/run-{run['id']}/`.")
            L.append("")
    if st.get("stubs"):
        L.append("## Stubbed")
        L.append("")
        for sb in st["stubs"]:
            line = f"- {sb['id']} {sb['text']} (direction {sb['direction']}, {short(sb['at'])})"
            if sb.get("unstubbed"):
                line += f" → unstubbed {short(sb.get('unstubbed_at'))}: {sb['unstubbed']}"
            L.append(line)
        L.append("")
    if st["questions"]:
        L.append("## Questions parked for the next boundary")
        L.append("")
        for q in st["questions"]:
            mark = "x" if q.get("answered") else " "
            L.append(f"- [{mark}] {question_label(q)}" + (f" → {q['answered']}" if q.get("answered") else ""))
        L.append("")
    if st["status"] == "closed":
        L.append(f"## Closed {short(st['closed_at'])}: {st['outcome']}")
        L.append("")
        c = st["close"]
        L.append(f"Tried: {c.get('tried') or '(see directions above)'}")
        L.append("")
        L.append(f"Learned: {c.get('learned') or '(nothing recorded)'}")
        L.append("")
        L.append(f"Thrown away: {c.get('thrown_away') or '(nothing recorded)'}")
        L.append("")
        if c.get("verdict"):
            L.append(f"Verdict on the question: {c['verdict'].upper()}" + (f" — {c['verdict_note']}" if c.get("verdict_note") else ""))
            L.append("")
        if c.get("unknown"):
            L.append("Still unknown:")
            for u in c["unknown"]:
                L.append(f"- {u}")
            L.append("")
    if st["sessions"]:
        L.append("## Sessions")
        L.append("")
        for s in st["sessions"]:
            L.append(f"- {s['session_id']} — {s.get('transcript_path') or '(no transcript path)'}")
        L.append("")
    return "\n".join(L)


def render_decisions(st):
    L = [f"# Decisions: {st['question']}", "", GENERATED, ""]
    L.append("Recovered at the end of a direction or recorded when the operator said so. Never the output of a dialog.")
    L.append("")
    if not st["decisions"]:
        L.append("(none yet)")
        L.append("")
    for d in st["decisions"]:
        L.append(f"## {d['id']} — {d['text']}")
        L.append("")
        L.append(f"- settled by: {by_label(d)}")
        L.append(f"- evidence: {evidence_label(d) or '(none)'}")
        if d.get("ask"):
            L.append(f"- question to ask: {d['ask']}")
        L.append(f"- direction: {d['direction']}, recorded {short(d['at'])}")
        if d.get("supersedes"):
            L.append(f"- supersedes: {', '.join(d['supersedes'])}")
        if d.get("superseded_by") is not None:
            L.append(f"- superseded by: {superseded_label(d)}")
        L.append("")
    return "\n".join(L)


def render_handoff(st, top=None):
    L = [f"# Handoff: {st['question']}", ""]
    L.append(f"<!-- scout-ahead handoff v{HANDOFF_VERSION}; plain markdown, fixed headings; written {short(now())}; generated from state.json, regenerate with `scout handoff` -->")
    L.append("")
    L.append("## Question")
    L.append("")
    L.append(st["question"])
    L.append("")
    if st.get("stakes"):
        L.append(f"Stakes: {st['stakes']}")
        L.append("")
    L.append("## Status")
    L.append("")
    status = st["status"] + (f", {st['outcome']}" if st.get("outcome") else "")
    L.append(f"{status}. {len(st['directions'])} direction(s) tried. Box: {box_line(st)}.")
    L.append("The box is what the scout spent, without tests, error handling or edge cases; it is not an estimate for the real build.")
    c = st.get("close") or {}
    fired = c.get("fired")
    if fired:
        for cid, t in criteria(st):
            L.append(f"{cid} {t}: " + ("fired" if cid in fired else "did not fire"))
    else:
        L += criteria_lines(st, "Keep criteria", "Kill criteria")
        if fired is not None:
            L.append("Criteria: none fired.")
    if c.get("verdict"):
        L.append(f"Verdict on the question: {c['verdict'].upper()}" + (f" — {c['verdict_note']}" if c.get("verdict_note") else ""))
    if c.get("blast_radius"):
        L.append(f"Blast radius: {c['blast_radius']}")
    if c.get("learned"):
        L.append("")
        L.append("Learned: " + c["learned"])
    L.append("")
    L.append("## Decisions")
    L.append("")
    L.append("| id | decision | settled by | evidence | superseded by |")
    L.append("|---|---|---|---|---|")
    for d in st["decisions"]:
        L.append(f"| {d['id']} | {d['text']} | {by_label(d)} | {evidence_label(d)} | {superseded_label(d)} |")
    if not st["decisions"]:
        L.append("| | (none recorded) | | | |")
    L.append("")
    L.append("settled by: operator = the operator said it, quoted or pointed to (a ledger's user-answered; why-log's testimony); code = the code or a measurement forced it (codebase-derived), proved when observed in this scout and inferred when reasoned from elsewhere; open = nobody settled it (deferred). A superseded decision stays as history.")
    L.append("")
    L.append("## Open questions")
    L.append("")
    opens = [d for d in open_decisions(st)] 
    qs = open_questions(st)
    if not opens and not qs:
        L.append("(none)")
    for d in opens:
        L.append(f"- {d['id']}: {d['text']}" + (f" — ask: {d['ask']}" if d.get("ask") else ""))
    for q in qs:
        L.append(f"- {question_label(q)}")
    L.append("")
    L.append("## Pointers")
    L.append("")
    L.append(f"- branch: `{st['branch'] or '(none)'}`" + branch_mark(st["branch"], st["base"], top))
    if st["branch"]:
        L.append(f"- `{st['branch']}` is evidence: re-run it, cite it, never merge it; what it proved is rebuilt under the receiving track's own rules.")
    L.append(f"- base: `{st['base'] or '?'}`")
    L.append(f"- head: `{st.get('head') or '?'}`")
    for i, d in enumerate(st["directions"], 1):
        outcome = direction_outcome(d)
        L.append(f"- direction {i}: {d['text']} (opened {short(d['opened_at'])}" + (f", closed {short(d['closed_at'])}" if d.get("closed_at") else "") + ")"
                 + (f" — {outcome}" if outcome else ""))
    # Arms fork from the scout's head, not its base; the arm line shows its own commit instead.
    for run in st.get("variants", []):
        for a in run["arms"]:
            L.append(f"- variant run {run['id']} arm v{a['i']}: `{a['branch']}`{branch_mark(a['branch'], None, top)} @ `{(a.get('commit') or '?')[:12]}`, ${a.get('cost_usd', 0):.2f}")
    for s in st["sessions"]:
        L.append(f"- transcript: {s.get('transcript_path') or s['session_id']}{transcript_mark(s.get('transcript_path'))}")
    L.append(f"- log: scouting/{st['slug']}/log.md")
    L.append(f"- decisions: scouting/{st['slug']}/decisions.md")
    L.append("")
    if c.get("repro"):
        L.append("## Reproducing")
        L.append("")
        L.append(c["repro"])
        L.append("")
    if st.get("prereg"):
        p = st["prereg"]
        L.append("## Pre-registration")
        L.append("")
        L.append(f"- question: {p['question']}")
        L.append(f"- arms: {p['arms']}")
        L.append(f"- runs: {p['runs']}")
        L.append(f"- pass rule: {p['pass_rule']}")
        L.append(f"- cost bound: ${p['cost_usd']}")
        L.append(f"- registered: {short(p['at'])} (before any scored run)")
        L.append("")
    L.append("## Thrown away")
    L.append("")
    L.append(c.get("thrown_away") or "(nothing recorded)")
    L.append("")
    L.append("## Still unknown")
    L.append("")
    for u in c.get("unknown") or []:
        L.append(f"- {u}")
    for sb in open_stubs(st):
        L.append(f"- stubbed: {sb['id']} {sb['text']}")
    if not c.get("unknown") and not open_stubs(st):
        L.append("(nothing recorded; a scout that names what it did not settle bounds its own authority)")
    L.append("")
    return "\n".join(L)


# ---------------------------------------------------------------- commands

def cmd_start(args):
    root = scouts_root(args)
    slug = args.slug or slugify(args.question)
    if (root / slug / STATE).exists():
        die(f"scout '{slug}' already exists")
    top = root.parent
    is_repo = subprocess.run(["git", "rev-parse", "--git-dir"], cwd=top, capture_output=True).returncode == 0
    base = git(["rev-parse", "HEAD"], cwd=top, check=False) if is_repo else ""
    branch = None
    if is_repo and not args.no_branch:
        branch = f"scout/{slug}"
        if args.worktree:
            wt = top.parent / f"{top.name}-scout-worktrees" / slug
            wt.parent.mkdir(parents=True, exist_ok=True)
            git(["worktree", "add", "-b", branch, str(wt)], cwd=top)
            top = wt
            root = wt / "scouting"
        else:
            git(["checkout", "-q", "-b", branch], cwd=top)
    st = {
        "slug": slug,
        "question": args.question,
        "stakes": args.stakes,
        "opened_at": now(),
        "closed_at": None,
        "status": "open",
        "outcome": None,
        "box": {"hours": args.hours, "usd": args.usd},
        "spent": {"hours": 0.0, "usd": 0.0},
        "kill": args.kill or [],
        "keep": args.keep or [],
        "branch": branch,
        "base": base,
        "head": None,
        "directions": [{"text": args.direction or args.question, "opened_at": now(), "entries": [], "closed_at": None}],
        "decisions": [],
        "questions": [],
        "variants": [],
        "sessions": [],
        "prereg": None,
        "close": {},
    }
    record_session(st, read_session_file(root))
    save(root, st)
    set_current(root, slug)
    print(f"opened scout '{slug}' at {root / slug}" + (f" on branch {branch}" if branch else ""))
    print("next: explore the code before deciding anything; `scout note` what it says.")


def _entry(st, kind, text):
    cur_direction(st)["entries"].append({"at": now(), "kind": kind, "text": text})


def cmd_note(args):
    read_stdin_fields(args)
    root = scouts_root(args)
    st = load(root, current_slug(root, args.scout))
    _entry(st, "note", args.text)
    save(root, st)
    print("noted")
    warn_box(st)


def cmd_question(args):
    read_stdin_fields(args)
    root = scouts_root(args)
    st = load(root, current_slug(root, args.scout))
    qid = f"Q{len(st['questions']) + 1}"
    st["questions"].append({"id": qid, "text": args.text, "assuming": args.assuming, "at": now(),
                            "direction": len(st["directions"]), "answered": None})
    _entry(st, "question parked", args.text)
    save(root, st)
    print(f"{qid} parked for the next boundary ({len(open_questions(st))} open)")
    warn_box(st)


def cmd_stub(args):
    read_stdin_fields(args)
    root = scouts_root(args)
    st = load(root, current_slug(root, args.scout))
    stubs = st.setdefault("stubs", [])
    sid = f"S{len(stubs) + 1}"
    stubs.append({"id": sid, "text": args.text, "at": now(), "direction": len(st["directions"]), "unstubbed": None})
    _entry(st, f"stubbed {sid}", args.text)
    save(root, st)
    print(f"{sid} recorded; re-read it against the question before any verdict ({len(open_stubs(st))} open)")


def cmd_unstub(args):
    read_stdin_fields(args)
    root = scouts_root(args)
